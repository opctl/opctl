package goop

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/opctl/opctl/sdks/go/model"
)

// StubUse declares an op stub in the caller's module. ModuleRef is a local ref
// anchored at ModuleRoot; Ref and Site preserve the declaration for diagnostics.
type StubUse struct {
	Name, Ref, ModuleRef, Site string
	Local                      bool
}

// GeneratedStubHeader identifies files owned by the op stub generator.
const GeneratedStubHeader = "// Code generated by opctl from the interface of op "

type stubType struct {
	base, name, path string
	schema           map[string]any
}
type stubRenderer struct{ types map[string]*stubType }

func stubHash(name string) string {
	sum := sha256.Sum256([]byte(name))
	return hex.EncodeToString(sum[:4])
}
func stubName(raw string) string {
	parts := strings.FieldsFunc(raw, func(r rune) bool { return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') })
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	name := strings.Join(parts, "")
	if name == "" {
		return "X" + stubHash(raw)
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "X" + name
	}
	return name
}
func stubNames(keys []string) map[string]string {
	counts := map[string]int{}
	for _, key := range keys {
		counts[stubName(key)]++
	}
	names := map[string]string{}
	for _, key := range keys {
		base := stubName(key)
		if counts[base] > 1 {
			base += "_" + stubHash(key)
		}
		names[key] = base
	}
	return names
}
func sortedStubKeys[T any](values map[string]T) []string {
	keys := make([]string, 0, len(values))
	for k := range values {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
func stubCommentText(text string) string {
	return strings.Map(func(r rune) rune {
		if r != '\n' && unicode.IsControl(r) || unicode.Is(unicode.Cf, r) {
			return -1
		}
		return r
	}, text)
}
func stubComment(out *bytes.Buffer, text string) {
	for _, line := range strings.Split(stubCommentText(text), "\n") {
		trimmed := strings.TrimSpace(line)
		// gofmt promotes legacy build comments even when they have a space.
		if strings.HasPrefix(trimmed, "+build") || strings.HasPrefix(trimmed, "go:build") {
			line = "Comment: " + line
		}
		fmt.Fprintf(out, "// %s\n", line)
	}
}
func stubParam(param *model.ParamSpec) (string, map[string]any) {
	data, _ := json.Marshal(param)
	var raw map[string]any
	_ = json.Unmarshal(data, &raw)
	for _, kind := range []string{"string", "number", "boolean", "dir", "file", "socket", "array", "object"} {
		if fields, ok := raw[kind].(map[string]any); ok {
			return kind, fields
		}
	}
	return "", nil
}
func stubSchemaSupported(schema map[string]any) bool {
	for _, key := range []string{"oneOf", "anyOf", "allOf", "$ref", "enum", "not"} {
		if _, ok := schema[key]; ok {
			return false
		}
	}
	_, ok := schema["type"].(string)
	return ok
}
func stubPath(parent, key string) string {
	return parent + "/" + strings.ReplaceAll(strings.ReplaceAll(key, "~", "~0"), "/", "~1")
}
func stubJSONProperties(properties map[string]any) bool {
	for key := range properties {
		if key == "" || key == "-" {
			return false
		}
		for _, char := range key {
			// Match encoding/json's tag-name rules, excluding the comma separator.
			if !unicode.IsLetter(char) && !unicode.IsDigit(char) && !strings.ContainsRune("!#$%&()*+-./:;<=>?@[]^_{|}~ ", char) {
				return false
			}
		}
	}
	return true
}

func (r *stubRenderer) collect(schema map[string]any, base, path string) {
	if !stubSchemaSupported(schema) {
		return
	}
	switch schema["type"] {
	case "array":
		item, _ := schema["items"].(map[string]any)
		r.collect(item, base+"Item", stubPath(path, "items"))
	case "object":
		if props, ok := schema["properties"].(map[string]any); ok {
			if !stubJSONProperties(props) {
				return
			}
			r.types[path] = &stubType{base: base, path: path, schema: schema}
			for _, key := range sortedStubKeys(props) {
				child, _ := props[key].(map[string]any)
				r.collect(child, base+stubName(key), stubPath(path, key))
			}
		} else {
			child, _ := schema["additionalProperties"].(map[string]any)
			r.collect(child, base+"Value", stubPath(path, "additionalProperties"))
		}
	}
}
func (r *stubRenderer) valueType(schema map[string]any, path string) string {
	if !stubSchemaSupported(schema) {
		return "any"
	}
	switch schema["type"] {
	case "string":
		return "string"
	case "integer":
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		item, _ := schema["items"].(map[string]any)
		return "[]" + r.valueType(item, stubPath(path, "items"))
	case "object":
		if node := r.types[path]; node != nil {
			return node.name
		}
		if _, ok := schema["properties"].(map[string]any); ok {
			return "map[string]any"
		}
		child, _ := schema["additionalProperties"].(map[string]any)
		return "map[string]" + r.valueType(child, stubPath(path, "additionalProperties"))
	default:
		return "any"
	}
}
func paramSchema(kind string, fields map[string]any) map[string]any {
	schema := map[string]any{"type": kind}
	constraints, _ := fields["constraints"].(map[string]any)
	for k, v := range constraints {
		schema[k] = v
	}
	return schema
}
func (r *stubRenderer) handleType(param *model.ParamSpec, path string) string {
	kind, fields := stubParam(param)
	switch kind {
	case "array":
		schema := paramSchema(kind, fields)
		item, _ := schema["items"].(map[string]any)
		return "opctl.Array[" + r.valueType(item, stubPath(path, "items")) + "]"
	case "object":
		return "opctl.Object[" + r.valueType(paramSchema(kind, fields), path) + "]"
	default:
		return "opctl." + stubName(kind)
	}
}
func stubRequired(p *model.ParamSpec) bool {
	_, fields := stubParam(p)
	return !p.DefaultPresent && fields["default"] == nil
}

// RenderStub renders a deterministic, dependency-free op stub from describe.
// Secret defaults are never included. Unsupported JSON schema subtrees use any.
func RenderStub(use StubUse, spec *model.OpSpec) ([]byte, error) {
	if !validStubName(use.Name) {
		return nil, fmt.Errorf("invalid op stub name %q", use.Name)
	}
	if spec == nil {
		return nil, fmt.Errorf("op stub %s: missing interface", use.Name)
	}
	r := stubRenderer{types: map[string]*stubType{}}
	groups := []struct {
		name   string
		params map[string]*model.ParamSpec
	}{{"Inputs", spec.Inputs}, {"Outputs", spec.Outputs}}
	for _, group := range groups {
		for _, key := range sortedStubKeys(group.params) {
			kind, fields := stubParam(group.params[key])
			if kind == "" {
				return nil, fmt.Errorf("op stub %s: parameter %q has no type", use.Name, key)
			}
			r.collect(paramSchema(kind, fields), group.name+stubName(key), stubPath(group.name, key))
		}
	}
	counts := map[string]int{"Inputs": 1, "Outputs": 1, "Call": 1}
	for _, node := range r.types {
		counts[node.base]++
	}
	for _, node := range r.types {
		node.name = node.base
		if counts[node.base] > 1 {
			node.name += "_" + stubHash(node.path)
		}
	}
	ref := use.Ref
	if use.Local {
		ref = use.ModuleRef
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "%s%s. DO NOT EDIT.\n\n", GeneratedStubHeader, strings.ReplaceAll(stubCommentText(ref), "\n", ""))
	stubComment(&out, fmt.Sprintf("Package %s calls op %s through its op stub.\n\n%s", use.Name, ref, spec.Description))
	fmt.Fprintf(&out, "package %s\n\nimport opctl %q\n\n", use.Name, "github.com/opctl/opctl/sdks/go/opspec/sdk")
	for _, group := range groups {
		stubComment(&out, group.name+" of op "+ref+".")
		fmt.Fprintf(&out, "type %s struct {\n", group.name)
		names := stubNames(sortedStubKeys(group.params))
		for _, key := range sortedStubKeys(group.params) {
			param := group.params[key]
			_, fields := stubParam(param)
			doc := names[key] + " is " + strings.ToLower(strings.TrimSuffix(group.name, "s")) + " " + strconv.Quote(key) + "."
			if group.name == "Inputs" {
				if stubRequired(param) {
					doc += " Required."
				} else if fields["isSecret"] == true {
					doc += " Has a default."
				} else {
					data, _ := json.Marshal(fields["default"])
					text := string(data)
					if len(text) > 60 {
						text = text[:60] + "..."
					}
					doc += " Default: " + text + "."
				}
			}
			if fields["isSecret"] == true {
				doc += " Secret."
			}
			if param.Description != "" {
				doc += "\n" + param.Description
			} else if text, ok := fields["description"].(string); ok {
				doc += "\n" + text
			}
			if constraints, ok := fields["constraints"]; ok {
				data, _ := json.Marshal(constraints)
				doc += "\nConstraints: " + string(data)
			}
			stubComment(&out, doc)
			fmt.Fprintf(&out, "%s %s\n", names[key], r.handleType(param, stubPath(group.name, key)))
		}
		out.WriteString("}\n\n")
	}
	for _, path := range sortedStubKeys(r.types) {
		node := r.types[path]
		props := node.schema["properties"].(map[string]any)
		names := stubNames(sortedStubKeys(props))
		required := map[string]bool{}
		if keys, ok := node.schema["required"].([]any); ok {
			for _, key := range keys {
				if key, ok := key.(string); ok {
					required[key] = true
				}
			}
		}
		stubComment(&out, node.name+" is the object value at "+path+".")
		fmt.Fprintf(&out, "type %s struct {\n", node.name)
		for _, key := range sortedStubKeys(props) {
			schema, _ := props[key].(map[string]any)
			tag := key
			if !required[key] {
				tag += ",omitempty"
			}
			fmt.Fprintf(&out, "%s %s %s\n", names[key], r.valueType(schema, stubPath(path, key)), strconv.Quote("json:"+strconv.Quote(tag)))
		}
		out.WriteString("}\n\n")
	}
	out.WriteString("// Call calls the op. Keep the returned call in the op graph.\nfunc Call(in Inputs) (opctl.OpCall, Outputs) {\nvar out Outputs\n")
	fmt.Fprintf(&out, "c := opctl.StubCall(%q, %q, %t, map[string]opctl.Handle{\n", use.Name, ref, use.Local)
	inputs := stubNames(sortedStubKeys(spec.Inputs))
	for _, key := range sortedStubKeys(spec.Inputs) {
		fmt.Fprintf(&out, "%q: in.%s,\n", key, inputs[key])
	}
	out.WriteString("}")
	for _, key := range sortedStubKeys(spec.Inputs) {
		if stubRequired(spec.Inputs[key]) {
			fmt.Fprintf(&out, ", %q", key)
		}
	}
	out.WriteString(")\n")
	outputs := stubNames(sortedStubKeys(spec.Outputs))
	for _, key := range sortedStubKeys(spec.Outputs) {
		fmt.Fprintf(&out, "c, out.%s = opctl.OpOutput[%s](c, %q)\n", outputs[key], r.handleType(spec.Outputs[key], stubPath("Outputs", key)), key)
	}
	out.WriteString("return c, out\n}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(string(formatted), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "//go:build") || strings.HasPrefix(line, "// +build") {
			return nil, fmt.Errorf("op stub %s: rendered source contains a build constraint", use.Name)
		}
	}
	return formatted, nil
}
